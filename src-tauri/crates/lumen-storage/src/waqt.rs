/// Parses `HH:MM` (24-hour) into minute-of-day, clamping cleanly.
#[must_use]
pub fn parse_hhmm_minutes(hhmm: &str, fallback: i32) -> i32 {
    let trimmed = hhmm.trim();
    if let Some((h_str, m_str)) = trimmed.split_once(':')
        && let (Ok(h), Ok(m)) = (h_str.parse::<i32>(), m_str.parse::<i32>())
        && (0..=23).contains(&h)
        && (0..=59).contains(&m)
    {
        return h * 60 + m;
    }
    fallback
}

/// Parses calendar/task time hints (`HH:MM`, `14:30`, `4:00 PM`, or ISO-8601 datetime) into minute-of-day.
#[must_use]
pub fn parse_event_minute_local(raw: &str) -> Option<i32> {
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        return None;
    }
    if let Ok(dt) = DateTime::parse_from_rfc3339(trimmed) {
        return Some((dt.hour() as i32) * 60 + (dt.minute() as i32));
    }
    if let Some(time_part) = trimmed.split('T').nth(1) {
        let hhmm = time_part.get(0..5)?;
        let min = parse_hhmm_minutes(hhmm, -1);
        if min >= 0 {
            return Some(min);
        }
    }
    let upper = trimmed.to_ascii_uppercase();
    let is_pm = upper.ends_with("PM");
    let is_am = upper.ends_with("AM");
    let core = upper.trim_end_matches("AM").trim_end_matches("PM").trim();
    if let Some((h_str, m_str)) = core.split_once(':')
        && let (Ok(mut h), Ok(m)) = (h_str.trim().parse::<i32>(), m_str.trim().parse::<i32>())
        && (0..=59).contains(&m)
    {
        if is_pm && h < 12 {
            h += 12;
        } else if is_am && h == 12 {
            h = 0;
        }
        if (0..=23).contains(&h) {
            return Some(h * 60 + m);
        }
    }
    None
}

fn format_compact_clock(min_of_day: i32) -> String {
    let wrapped = min_of_day.rem_euclid(1440);
    let h24 = wrapped / 60;
    let m = wrapped % 60;
    let h12 = match h24 % 12 {
        0 => 12,
        v => v,
    };
    format!("{h12}:{m:02}")
}

fn format_duration_short(mins: i32) -> String {
    let clamped = mins.max(0);
    let h = clamped / 60;
    let m = clamped % 60;
    if h > 0 && m > 0 {
        format!("{h}h {m}m")
    } else if h > 0 {
        format!("{h}h")
    } else {
        format!("{m}m")
    }
}

fn resolve_length_hint_kind(free_min: i32) -> String {
    if free_min >= 90 {
        "deep_work".to_string()
    } else if free_min >= 30 {
        "quick_tasks".to_string()
    } else {
        "short_break".to_string()
    }
}

fn dhaka_offset() -> FixedOffset {
    FixedOffset::east_opt(6 * 3600).unwrap_or_else(|| FixedOffset::east_opt(0).expect("offset"))
}

