fn infer_block_id(minute_of_day: i32, blocks: &[(String, i32, i32)]) -> String {
    for (id, start, end) in blocks {
        if minute_of_day >= *start && minute_of_day < *end {
            return id.clone();
        }
    }
    if let Some((first_id, first_start, _)) = blocks.first()
        && minute_of_day < *first_start
    {
        return first_id.clone();
    }
    blocks
        .last()
        .map(|(id, _, _)| id.clone())
        .unwrap_or_else(|| "isha".to_string())
}

fn is_yesterday_unfinished_task(
    task: &TaskItem,
    today_date: chrono::NaiveDate,
    now_local: DateTime<FixedOffset>,
    fajr_min: i32,
    rollover_at_fajr: bool,
) -> bool {
    if task.done
        || task
            .block_id
            .as_deref()
            .unwrap_or("")
            .starts_with("tomorrow:")
    {
        return false;
    }
    let Ok(dt) = DateTime::parse_from_rfc3339(&task.created_at) else {
        return false;
    };
    let created_local = dt.with_timezone(now_local.offset());
    let cutoff = if rollover_at_fajr {
        let fajr_hour = (fajr_min / 60).clamp(0, 23) as u32;
        let fajr_minute = (fajr_min % 60).clamp(0, 59) as u32;
        let base_day = if (now_local.hour() as i32) * 60 + (now_local.minute() as i32) < fajr_min {
            today_date - ChronoDuration::days(1)
        } else {
            today_date
        };
        base_day
            .and_hms_opt(fajr_hour, fajr_minute, 0)
            .and_then(|ndt| ndt.and_local_timezone(*now_local.offset()).single())
    } else {
        today_date
            .and_hms_opt(0, 0, 0)
            .and_then(|ndt| ndt.and_local_timezone(*now_local.offset()).single())
    };
    cutoff.is_some_and(|c| created_local < c)
}

/// Computes unfinished task count from before today's Fajr rollover boundary.
#[must_use]
pub fn count_unfinished_yesterday_tasks(
    tasks: &[TaskItem],
    now_utc: DateTime<Utc>,
    fajr_min: i32,
    rollover_at_fajr: bool,
) -> usize {
    let now_local = now_utc.with_timezone(&dhaka_offset());
    let today_date = now_local.date_naive();
    tasks
        .iter()
        .filter(|t| {
            is_yesterday_unfinished_task(t, today_date, now_local, fajr_min, rollover_at_fajr)
        })
        .count()
}

fn build_rhythm_anchors_for_block(
    block_id: &str,
    items: &[WaqtBlockItem],
    input: &WaqtComputeInput<'_>,
) -> Vec<WaqtGhostAnchor> {
    input
        .rhythm_anchors
        .iter()
        .filter(|a| a.enabled && a.block_id == block_id)
        .filter(|a| {
            // Omit anchor if already materialized as an item with matching title inside this block
            let lower = a.title.to_ascii_lowercase();
            !items
                .iter()
                .any(|item| item.title.to_ascii_lowercase() == lower)
        })
        .map(|a| {
            let progress_label = if a.kind == "water" {
                Some(format!(
                    "{}/{} ml",
                    input.water_today_ml.max(0),
                    input.water_goal_ml.max(250)
                ))
            } else {
                None
            };
            WaqtGhostAnchor {
                id: a.id.clone(),
                title: a.title.clone(),
                kind: a.kind.clone(),
                estimate_min: a.estimate_min.max(5),
                block_id: a.block_id.clone(),
                progress_label,
                is_user_template: a.is_user_template,
            }
        })
        .collect()
}

struct SuggestionQuery<'a> {
    block_id: &'a str,
    free_capacity_min: i32,
    has_calendar_event: bool,
    today_ymd: &'a str,
    yesterday_tasks: &'a [&'a TaskItem],
    inbox_tasks: &'a [&'a TaskItem],
    block_rhythm: &'a [WaqtGhostAnchor],
    dismissed_set: &'a HashSet<&'a str>,
    recent_texts: &'a HashSet<String>,
}

fn select_deterministic_suggestion(
    q: SuggestionQuery<'_>,
    used_task_ids: &mut HashSet<i64>,
    used_texts: &mut HashSet<String>,
) -> Option<WaqtSuggestion> {
    let SuggestionQuery {
        block_id,
        free_capacity_min,
        has_calendar_event,
        today_ymd,
        yesterday_tasks,
        inbox_tasks,
        block_rhythm,
        dismissed_set,
        recent_texts,
    } = q;
    let mut candidates: Vec<WaqtSuggestion> = Vec::new();

    // 1. Due today tasks (unassigned first, matching today's date)
    for t in inbox_tasks {
        if t.due_at
            .as_deref()
            .is_some_and(|d| d.starts_with(today_ymd))
            && (t.estimate_min as i32) <= free_capacity_min.max(15)
        {
            candidates.push(WaqtSuggestion {
                id: format!("due:{}:{}", block_id, t.id),
                text: format!("{} · {}m", t.title, t.estimate_min.max(5)),
                source: "due_today".to_string(),
                kind: t.kind.clone(),
                estimate_min: t.estimate_min.max(5),
                task_id: Some(t.id),
                block_id: block_id.to_string(),
            });
        }
    }

    // 2. Yesterday's unfinished tasks
    for t in yesterday_tasks {
        if (t.estimate_min as i32) <= free_capacity_min.max(15) {
            candidates.push(WaqtSuggestion {
                id: format!("yest:{}:{}", block_id, t.id),
                text: format!("{} · {}m", t.title, t.estimate_min.max(5)),
                source: "yesterday_unfinished".to_string(),
                kind: t.kind.clone(),
                estimate_min: t.estimate_min.max(5),
                task_id: Some(t.id),
                block_id: block_id.to_string(),
            });
        }
    }

    // 3. Calendar gap or block-length rule (with secondary non-repeating variants)
    if has_calendar_event || free_capacity_min >= 30 {
        let gap_options: Vec<(&str, i64, &str, &str)> = if free_capacity_min >= 90 {
            vec![
                ("Deep work · 60m", 60, "deep_work", "task"),
                ("Focus sprint · 45m", 45, "focus_sprint", "task"),
                ("Plan milestone · 30m", 30, "milestone", "task"),
            ]
        } else if free_capacity_min >= 30 {
            vec![
                ("Quick tasks · 20m", 20, "quick_tasks", "task"),
                ("Inbox sweep · 15m", 15, "inbox_sweep", "task"),
            ]
        } else {
            vec![
                ("Break / walk · 10m", 10, "short_break", "habit"),
                ("Screen rest · 5m", 5, "screen_rest", "habit"),
            ]
        };
        for (text, est, slug, kind) in gap_options {
            candidates.push(WaqtSuggestion {
                id: format!("gap:{}:{}", block_id, slug),
                text: text.to_string(),
                source: "calendar_gap".to_string(),
                kind: kind.to_string(),
                estimate_min: est,
                task_id: None,
                block_id: block_id.to_string(),
            });
        }
    }

    // 4. Inbox tasks fitting free gap
    for t in inbox_tasks {
        if (t.estimate_min as i32) + 5 <= free_capacity_min {
            candidates.push(WaqtSuggestion {
                id: format!("inbox:{}:{}", block_id, t.id),
                text: format!("{} · {}m", t.title, t.estimate_min.max(5)),
                source: "inbox".to_string(),
                kind: t.kind.clone(),
                estimate_min: t.estimate_min.max(5),
                task_id: Some(t.id),
                block_id: block_id.to_string(),
            });
        }
    }

    // 5. Enabled rhythm anchors not yet checked off in this block
    for r in block_rhythm {
        candidates.push(WaqtSuggestion {
            id: format!("rhythm:{}:{}", block_id, r.id),
            text: r.title.clone(),
            source: "rhythm".to_string(),
            kind: r.kind.clone(),
            estimate_min: r.estimate_min.max(5),
            task_id: None,
            block_id: block_id.to_string(),
        });
    }

    for cand in candidates {
        if dismissed_set.contains(cand.id.as_str()) {
            continue;
        }
        let lower = cand.text.to_ascii_lowercase();
        if recent_texts.contains(&lower) || used_texts.contains(&lower) {
            continue;
        }
        if let Some(tid) = cand.task_id
            && used_task_ids.contains(&tid)
        {
            continue;
        }
        if let Some(tid) = cand.task_id {
            used_task_ids.insert(tid);
        }
        used_texts.insert(lower);
        return Some(cand);
    }
    None
}

/// Computes deterministic "Plan my day" assignments matching each inbox task to the
/// tightest fitting non-past Waqt block without modifying SQLite.
#[must_use]
pub fn compute_plan_my_day_preview(
    unplanned: &[TaskItem],
    blocks: &[WaqtBlockView],
) -> Vec<WaqtPlanAssignment> {
    let mut remaining_free: Vec<(usize, i32)> = blocks
        .iter()
        .enumerate()
        .filter(|(_, b)| !b.is_past)
        .map(|(idx, b)| (idx, b.free_capacity_min))
        .collect();

    let mut sorted_tasks: Vec<&TaskItem> = unplanned
        .iter()
        .filter(|t| !t.done && !t.block_id.as_deref().unwrap_or("").starts_with("tomorrow:"))
        .collect();
    sorted_tasks.sort_by_key(|t| (i32::from(t.due_at.is_none()), t.sort_order, t.id));

    let mut plan = Vec::new();
    for task in sorted_tasks {
        let est = task.estimate_min.max(5);
        let need = (est as i32) + 5;
        // Prefer the fitting block whose remaining capacity best matches `need` (minimizes waste).
        let mut best_pos: Option<usize> = None;
        let mut best_score = i32::MAX;
        for (pos, &(_bidx, rem)) in remaining_free.iter().enumerate() {
            if rem >= need {
                let waste = rem - need;
                if waste < best_score {
                    best_score = waste;
                    best_pos = Some(pos);
                }
            }
        }
        if let Some(pos) = best_pos {
            let (bidx, rem) = remaining_free[pos];
            remaining_free[pos].1 = rem - need;
            let blk = &blocks[bidx];
            plan.push(WaqtPlanAssignment {
                task_id: task.id,
                task_title: task.title.clone(),
                prev_block_id: task.block_id.clone(),
                target_block_id: blk.id.clone(),
                target_block_name: blk.name.clone(),
                estimate_min: est,
            });
        }
    }
    plan
}

/// Derives full Waqt Timeline state deterministically from PrayerSchedule, SQLite tasks, events and logs.
#[must_use]
pub fn compute_waqt_timeline(input: &WaqtComputeInput<'_>) -> WaqtTimelineState {
    let now_local = input.now_utc.with_timezone(&dhaka_offset());
    let now_min = (now_local.hour() as i32) * 60 + (now_local.minute() as i32);
    let today_date = now_local.date_naive();
    let today_ymd = today_date.format("%Y-%m-%d").to_string();
    let date_label = now_local.format("%a %-d %b").to_string();

    let anchors = resolve_anchors(input);
    let fajr_min = anchors[0].minute_of_day;
    let dhuhr_min = anchors[1].minute_of_day;
    let asr_min = anchors[2].minute_of_day;
    let maghrib_min = anchors[3].minute_of_day;
    let isha_min = anchors[4].minute_of_day;
    let is_after_isha = now_min >= isha_min;

    let bedtime_raw = parse_hhmm_minutes(input.bedtime_hhmm, 23 * 60 + 30);
    let night_end_min = if bedtime_raw <= isha_min {
        (bedtime_raw + 24 * 60).max(isha_min + 60)
    } else {
        bedtime_raw
    };

    let rail_start_min = fajr_min;
    let rail_end_min = night_end_min;
    let sun_progress_pct = (((now_min - rail_start_min) as f32
        / (rail_end_min - rail_start_min).max(1) as f32)
        * 100.0)
        .clamp(0.0, 100.0)
        .round() as u8;

    let mut block_defs: Vec<(String, String, String, i32, i32)> = vec![
        (
            "fajr".to_string(),
            "Morning".to_string(),
            format!("Fajr {}", format_compact_clock(fajr_min)),
            fajr_min,
            dhuhr_min,
        ),
        (
            "dhuhr".to_string(),
            if input.is_friday {
                "Jumu'ah".to_string()
            } else {
                "Midday".to_string()
            },
            format!(
                "{} {}",
                if input.is_friday { "Jumu'ah" } else { "Dhuhr" },
                format_compact_clock(dhuhr_min)
            ),
            dhuhr_min,
            asr_min,
        ),
        (
            "asr".to_string(),
            "Afternoon".to_string(),
            format!("Asr {}", format_compact_clock(asr_min)),
            asr_min,
            maghrib_min,
        ),
        (
            "maghrib".to_string(),
            "Evening".to_string(),
            format!("Maghrib {}", format_compact_clock(maghrib_min)),
            maghrib_min,
            isha_min,
        ),
        (
            "isha".to_string(),
            if input.is_ramadan && input.ramadan_taraweeh {
                "Taraweeh".to_string()
            } else {
                "Night".to_string()
            },
            format!("Isha {}", format_compact_clock(isha_min)),
            isha_min,
            night_end_min,
        ),
    ];

    if input.is_ramadan && input.ramadan_taraweeh && night_end_min > isha_min + 90 {
        let taraweeh_end = isha_min + 75;
        if let Some(isha_def) = block_defs.get_mut(4) {
            isha_def.4 = taraweeh_end;
        }
    }

    let block_ranges: Vec<(String, i32, i32)> = block_defs
        .iter()
        .map(|(id, _, _, s, e)| (id.clone(), *s, *e))
        .collect();

    let mut items_by_block: HashMap<String, Vec<WaqtBlockItem>> = HashMap::new();
    let mut unplanned: Vec<TaskItem> = Vec::new();
    let mut tomorrow_tasks: Vec<WaqtBlockItem> = Vec::new();
    let mut active_task_count = 0usize;
    let mut done_task_count = 0usize;

    for task in input.tasks {
        if let Some(b) = task.block_id.as_deref()
            && let Some(target_day_blk) = b.strip_prefix("tomorrow:")
        {
            tomorrow_tasks.push(WaqtBlockItem {
                id: task.id,
                title: task.title.clone(),
                kind: task.kind.clone(),
                source: task.source.clone(),
                estimate_min: task.estimate_min.max(5),
                done: task.done,
                done_at: task.done_at.clone(),
                fixed: task.fixed,
                start_at: Some(target_day_blk.to_string()),
                slot_start_min: fajr_min,
                slot_end_min: fajr_min + (task.estimate_min.max(5) as i32),
                client: task.client.clone(),
                calendar_event_id: task.calendar_event_id,
                sort_order: task.sort_order,
            });
            continue;
        }

        if task.done {
            done_task_count += 1;
        } else {
            active_task_count += 1;
        }

        let explicit_block = task.block_id.clone();
        let inferred_from_time = task
            .start_at
            .as_deref()
            .and_then(parse_event_minute_local)
            .map(|m| infer_block_id(m, &block_ranges));

        if let Some(bid) = explicit_block.or(inferred_from_time) {
            let block_start = block_ranges
                .iter()
                .find(|(id, _, _)| id == &bid)
                .map(|(_, s, _)| *s)
                .unwrap_or(fajr_min);
            let slot_start = task
                .start_at
                .as_deref()
                .and_then(parse_event_minute_local)
                .unwrap_or(block_start);
            let est = task.estimate_min.max(5);
            items_by_block.entry(bid).or_default().push(WaqtBlockItem {
                id: task.id,
                title: task.title.clone(),
                kind: task.kind.clone(),
                source: task.source.clone(),
                estimate_min: est,
                done: task.done,
                done_at: task.done_at.clone(),
                fixed: task.fixed,
                start_at: task.start_at.clone(),
                slot_start_min: slot_start,
                slot_end_min: slot_start + est as i32,
                client: task.client.clone(),
                calendar_event_id: task.calendar_event_id,
                sort_order: task.sort_order,
            });
        } else {
            unplanned.push(task.clone());
        }
    }

    for ev in input.calendar_events {
        let already_imported = input
            .tasks
            .iter()
            .any(|t| t.calendar_event_id == Some(ev.id));
        if already_imported {
            continue;
        }
        let start_min = parse_event_minute_local(&ev.start_at).unwrap_or(dhuhr_min);
        let bid = infer_block_id(start_min, &block_ranges);
        items_by_block.entry(bid).or_default().push(WaqtBlockItem {
            id: -ev.id,
            title: ev.title.clone(),
            kind: "meeting".to_string(),
            source: "calendar".to_string(),
            estimate_min: 30,
            done: now_min >= start_min + 30,
            done_at: None,
            fixed: true,
            start_at: Some(ev.start_at.clone()),
            slot_start_min: start_min,
            slot_end_min: start_min + 30,
            client: None,
            calendar_event_id: Some(ev.id),
            sort_order: start_min as i64,
        });
    }

    let mut focus_minutes_per_block: HashMap<String, i32> = HashMap::new();
    let mut focus_bars = vec![12_u32; 10];
    let mut logged_focus_total = 0_i32;
    let mut logged_prayers: HashSet<String> = HashSet::new();

    for log in input.activity_log {
        let start_m = parse_event_minute_local(&log.start_at).unwrap_or(now_min);
        let bid = infer_block_id(start_m, &block_ranges);
        if log.kind == "focus" {
            let end_m = log
                .end_at
                .as_deref()
                .and_then(parse_event_minute_local)
                .unwrap_or(now_min);
            let dur = (end_m - start_m).clamp(1, 180);
            *focus_minutes_per_block.entry(bid).or_insert(0) += dur;
            logged_focus_total += dur;

            let ratio = ((start_m - rail_start_min) as f32
                / (rail_end_min - rail_start_min).max(1) as f32)
                .clamp(0.0, 0.99);
            let bucket = (ratio * 10.0).floor() as usize;
            if let Some(bar) = focus_bars.get_mut(bucket) {
                *bar = (*bar + (dur as u32) * 2).min(100);
            }
        } else if log.kind == "prayer" {
            if let Some(ref_id) = log.ref_id.as_deref() {
                logged_prayers.insert(ref_id.to_string());
            } else {
                logged_prayers.insert(bid);
            }
        }
    }

    let total_focus_min = if logged_focus_total > 0 {
        logged_focus_total
    } else {
        input.pomodoro_focus_min
    };
    if total_focus_min > 0 && focus_bars.iter().all(|&b| b == 12) {
        let ratio = ((now_min - rail_start_min) as f32
            / (rail_end_min - rail_start_min).max(1) as f32)
            .clamp(0.0, 0.99);
        let active_bucket = (ratio * 10.0).floor() as usize;
        for (i, bar) in focus_bars.iter_mut().enumerate() {
            if i <= active_bucket {
                *bar = match i % 3 {
                    0 => 58,
                    1 => 82,
                    _ => 44,
                };
            }
        }
    }

    let mut active_block_id = block_defs
        .last()
        .map(|(id, ..)| id.clone())
        .unwrap_or_else(|| "isha".to_string());

    let yesterday_unfinished_refs: Vec<&TaskItem> = input
        .tasks
        .iter()
        .filter(|t| {
            is_yesterday_unfinished_task(t, today_date, now_local, fajr_min, input.rollover_at_fajr)
        })
        .collect();
    let inbox_refs: Vec<&TaskItem> = unplanned.iter().filter(|t| !t.done).collect();
    let dismissed_set: HashSet<&str> = input
        .dismissed_suggestions
        .iter()
        .map(String::as_str)
        .collect();
    let recent_set: HashSet<String> = input
        .recent_suggestion_texts
        .iter()
        .map(|s| s.to_ascii_lowercase())
        .collect();

    let mut blocks: Vec<WaqtBlockView> = Vec::with_capacity(block_defs.len());
    let mut current_block_index: Option<usize> = None;

    for (idx, (id, default_name, prayer_label, start_min, end_min)) in block_defs.iter().enumerate()
    {
        let name = input
            .custom_block_names
            .get(id)
            .cloned()
            .filter(|s| !s.trim().is_empty())
            .unwrap_or_else(|| default_name.clone());

        let is_current = now_min >= *start_min && now_min < *end_min
            || (idx == 0 && now_min < *start_min)
            || (idx == block_defs.len() - 1 && now_min >= *start_min);
        if is_current {
            active_block_id = id.clone();
            current_block_index = Some(idx);
        }
        let is_past = now_min >= *end_min && idx < block_defs.len() - 1;
        let duration = (*end_min - *start_min).max(1);
        let remaining_min = (*end_min - now_min).max(0);

        let mut items = items_by_block.remove(id).unwrap_or_default();
        items.sort_by_key(|it| (!it.fixed, it.sort_order, it.id));

        let mut cursor = *start_min;
        let mut fixed_intervals: Vec<(i32, i32)> = items
            .iter()
            .filter(|i| i.fixed)
            .map(|i| (i.slot_start_min, i.slot_end_min))
            .collect();
        fixed_intervals.sort_by_key(|v| v.0);

        for item in items.iter_mut().filter(|i| !i.fixed) {
            let est = item.estimate_min.max(5) as i32;
            loop {
                let conflict = fixed_intervals
                    .iter()
                    .find(|(fs, fe)| cursor < *fe && (cursor + est) > *fs)
                    .copied();
                if let Some((_, fe)) = conflict {
                    cursor = fe + 5;
                } else {
                    break;
                }
            }
            item.slot_start_min = cursor;
            item.slot_end_min = cursor + est;
            cursor += est + 5;
        }

        let used_capacity_min: i32 = items
            .iter()
            .map(|i| {
                let est = i.estimate_min.max(5) as i32;
                if i.fixed { est } else { est + 5 }
            })
            .sum();

        let effective_window = if is_current {
            remaining_min.max(15)
        } else {
            duration
        };
        let free_capacity_min = effective_window - used_capacity_min;
        let capacity_status = if free_capacity_min < 0 {
            WaqtCapacityStatus::Overbooked
        } else if free_capacity_min < 15 {
            WaqtCapacityStatus::Tight
        } else {
            WaqtCapacityStatus::Free
        };

        let fill_ratio_pct = ((used_capacity_min as f32 / effective_window.max(1) as f32) * 100.0)
            .clamp(0.0, 100.0)
            .round() as u8;
        let focus_minutes = *focus_minutes_per_block.get(id).unwrap_or(&0);
        let logged_prayer_done = is_past || logged_prayers.contains(id);

        let status_text = if is_past {
            if focus_minutes > 0 {
                format!("Done · focus {}", format_duration_short(focus_minutes))
            } else {
                "Done · Prayer ✓".to_string()
            }
        } else if capacity_status == WaqtCapacityStatus::Overbooked {
            "No room".to_string()
        } else if capacity_status == WaqtCapacityStatus::Tight {
            "Almost full".to_string()
        } else if is_current {
            format!("{} left", format_duration_short(remaining_min))
        } else if items.is_empty() {
            format!("Free {}", format_duration_short(free_capacity_min))
        } else {
            format!("{} free", format_duration_short(free_capacity_min))
        };

        let range_label = if id == "isha" {
            format!("{} – bed", format_compact_clock(*start_min))
        } else {
            format!(
                "{} – {}",
                format_compact_clock(*start_min),
                format_compact_clock(*end_min)
            )
        };

        let rhythm_anchors = build_rhythm_anchors_for_block(id, &items, input);

        blocks.push(WaqtBlockView {
            id: id.clone(),
            default_name: default_name.clone(),
            name,
            prayer_label: prayer_label.clone(),
            start_min: *start_min,
            end_min: *end_min,
            range_label,
            is_past,
            is_current,
            fill_ratio_pct,
            remaining_min,
            free_capacity_min,
            used_capacity_min,
            capacity_status,
            length_hint_kind: resolve_length_hint_kind(free_capacity_min),
            focus_minutes,
            logged_focus_min: focus_minutes,
            logged_prayer_done,
            status_text,
            items,
            suggestion: None,
            rhythm_anchors,
        });
    }

    // Deterministic Suggestion Engine: max 1 suggestion per block, ONLY on current + next block.
    if !input.quiet_mode
        && let Some(cur_idx) = current_block_index
    {
        let mut used_task_ids: HashSet<i64> = HashSet::new();
        let mut used_texts: HashSet<String> = HashSet::new();
        let eligible_indices = [Some(cur_idx), blocks.get(cur_idx + 1).map(|_| cur_idx + 1)];
        for maybe_idx in eligible_indices.into_iter().flatten() {
            if let Some(blk) = blocks.get_mut(maybe_idx) {
                let blk_marker = format!("block:{}", blk.id);
                if dismissed_set.contains(blk_marker.as_str()) {
                    continue;
                }
                let has_cal = blk.items.iter().any(|i| i.source == "calendar");
                blk.suggestion = select_deterministic_suggestion(
                    SuggestionQuery {
                        block_id: &blk.id,
                        free_capacity_min: blk.free_capacity_min,
                        has_calendar_event: has_cal,
                        today_ymd: &today_ymd,
                        yesterday_tasks: &yesterday_unfinished_refs,
                        inbox_tasks: &inbox_refs,
                        block_rhythm: &blk.rhythm_anchors,
                        dismissed_set: &dismissed_set,
                        recent_texts: &recent_set,
                    },
                    &mut used_task_ids,
                    &mut used_texts,
                );
            }
        }
    }

    let next_anchor = anchors
        .iter()
        .find(|a| a.minute_of_day > now_min)
        .unwrap_or(&anchors[0]);
    let next_prayer_in_min = if next_anchor.minute_of_day > now_min {
        next_anchor.minute_of_day - now_min
    } else {
        (next_anchor.minute_of_day + 1440) - now_min
    };
    let prayers_done_count = anchors
        .iter()
        .filter(|a| a.minute_of_day <= now_min)
        .count();

    let yesterday_rollover_count = count_unfinished_yesterday_tasks(
        input.tasks,
        input.now_utc,
        fajr_min,
        input.rollover_at_fajr,
    );

    // Ordered remaining undone tasks across current+future blocks for Focus card & "then: X"
    let ordered_undone: Vec<(i64, String)> = blocks
        .iter()
        .filter(|b| !b.is_past)
        .flat_map(|b| b.items.iter())
        .filter(|i| !i.done && i.id > 0)
        .map(|i| (i.id, i.title.clone()))
        .collect();

    let resolved_focus_id = input
        .current_focus_task_id
        .filter(|fid| ordered_undone.iter().any(|(id, _)| id == fid))
        .or_else(|| ordered_undone.first().map(|(id, _)| *id));

    let focus_next = ordered_undone
        .iter()
        .find(|(id, _)| Some(*id) != resolved_focus_id)
        .cloned();

    let total_planned_min: i32 = blocks
        .iter()
        .filter(|b| !b.is_past)
        .map(|b| b.used_capacity_min)
        .sum();
    let total_free_min: i32 = blocks
        .iter()
        .filter(|b| !b.is_past)
        .map(|b| b.free_capacity_min.max(0))
        .sum();
    let total_deficit_min: i32 = blocks
        .iter()
        .filter(|b| !b.is_past && b.free_capacity_min < 0)
        .map(|b| -b.free_capacity_min)
        .sum();
    let day_is_overbooked = total_deficit_min > 0 && total_deficit_min >= total_free_min;

    let all_tasks_done = active_task_count == 0
        && (done_task_count > 0 || blocks.iter().flat_map(|b| b.items.iter()).any(|i| i.done));

    let tomorrow_blocks: Vec<WaqtTomorrowBlock> = blocks
        .iter()
        .map(|b| WaqtTomorrowBlock {
            id: b.id.clone(),
            name: b.name.clone(),
            range_label: b.range_label.clone(),
            task_count: tomorrow_tasks
                .iter()
                .filter(|t| t.start_at.as_deref() == Some(b.id.as_str()))
                .count(),
        })
        .collect();

    let plan_my_day_preview = compute_plan_my_day_preview(&unplanned, &blocks);

    WaqtTimelineState {
        date_label,
        now_min,
        rail_start_min,
        rail_end_min,
        sun_progress_pct,
        is_friday: input.is_friday,
        is_ramadan: input.is_ramadan,
        is_after_isha,
        all_tasks_done,
        sehri_min: input.sehri_min,
        iftar_min: input.iftar_min,
        location_configured: input.location_configured,
        active_block_id,
        next_prayer_name: next_anchor.label.clone(),
        next_prayer_in_min,
        current_focus_task_id: resolved_focus_id,
        focus_next_task_id: focus_next.as_ref().map(|v| v.0),
        focus_next_task_title: focus_next.map(|v| v.1),
        yesterday_rollover_count,
        total_focus_min,
        total_planned_min,
        total_free_min,
        day_is_overbooked,
        prayers_done_count,
        water_today_ml: input.water_today_ml,
        water_goal_ml: input.water_goal_ml.max(250),
        focus_bars,
        blocks,
        unplanned,
        tomorrow_blocks,
        tomorrow_tasks,
        plan_my_day_preview,
        activity_log: input.activity_log.to_vec(),
    }
}

